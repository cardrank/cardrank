// Command cgen generates the combination lookup tables in combin.go.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
)

func main() {
	out := flag.String("out", "combin.go", "out")
	flag.Parse()
	buf := new(bytes.Buffer)
	fmt.Fprintln(buf, "// Code generated by internal/cmd/cgen. DO NOT EDIT.")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "package cardrank")
	for _, nk := range [][2]int{{4, 2}, {5, 2}, {5, 3}, {6, 2}, {6, 5}, {7, 5}} {
		gen(buf, nk[0], nk[1])
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// gen writes the table for taking n, choosing k, where each row is the k
// chosen indices followed by the unused indices.
func gen(buf *bytes.Buffer, n, k int) {
	var rows [][]int
	combin(n, k, 0, nil, func(v []int) {
		row := slices.Clone(v)
		for i := range n {
			if !slices.Contains(v, i) {
				row = append(row, i)
			}
		}
		rows = append(rows, row)
	})
	fmt.Fprintln(buf)
	fmt.Fprintf(buf, "// t%dc%d is used for taking %d, choosing %d.\n", n, k, n, k)
	fmt.Fprintf(buf, "var t%dc%d = [%d][%d]uint8{\n", n, k, len(rows), n)
	for _, row := range rows {
		fmt.Fprint(buf, "\t{")
		for i, x := range row {
			if i != 0 {
				fmt.Fprint(buf, ", ")
			}
			fmt.Fprint(buf, x)
		}
		fmt.Fprintln(buf, "},")
	}
	fmt.Fprintln(buf, "}")
}

// combin calls f with each combination of k indices from [start, n), in
// lexical order.
func combin(n, k, start int, v []int, f func([]int)) {
	if len(v) == k {
		f(v)
		return
	}
	for i := start; i < n; i++ {
		combin(n, k, i+1, append(v, i), f)
	}
}
